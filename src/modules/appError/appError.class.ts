export const errorMap = {
  INVALID_CREDENTIALS: 401,
  INVALID_BODY: 400,
  INVALID_PARAMS: 422,

  INVALID_USER_ID: 404,
  INVALID_PASSWORD: 401,

  INVALID_SEARCH_LIMITS: 422,
  INVALID_SEARCH_OPTIONS: 422,

  SEARCH_INVALID_SORT_ORDER: 422,
  SEARCH_EXCEEDS_LIMIT: 422,
  SEARCH_MIN_PRICE_EXCEEDS_MAX: 422,
  SEARCH_INVALID_SORT_BY: 422,
  SEARCH_MUST_BE_STRING: 422,
  INVALID_SEARCH_PRICES: 422,

  CREATE_PRODUCT_INVALID_TITLE: 422,
  CREATE_PRODUCT_INVALID_STOCK: 422,
  CREATE_PRODUCT_INVALID_DESCRIPTION: 422,
  CREATE_PRODUCT_INVALID_PRICE: 422,

  INVALID_REFRESH_TOKEN: 401,
  REFRESH_TOKEN_REVOKE_ERROR: 500,

  LOGIN_REQUIRED: 422,
  EMAIL_REQUIRED: 422,
  PASSWORD_REQUIRED: 422,
  INVALID_LOGIN_LENGTH: 422,
  INVALID_PASSWORD_LENGTH: 422,
  INVALID_EMAIL: 422,

  INVALID_TOKEN: 401,
  UNKNOWN_SERVER_ERROR: 500,
};

export type ErrorCode = keyof typeof errorMap;

export class AppError extends Error {
  public statusCode: number;
  public code: string;

  constructor(code: ErrorCode) {
    super(code);

    this.name = "AppError";
    this.code = code;
    this.statusCode = errorMap[code];

    Error.captureStackTrace(this, this.constructor);
  }
}
